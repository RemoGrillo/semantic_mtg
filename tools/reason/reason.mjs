#!/usr/bin/env node
// OWL DL reasoning with ROBOT + HermiT on a portable JRE (no system install).
//   npm run reason            → bootstrap .tools/ if needed, then:
//     1. merge TBox (all modules + vocab) via catalog-v001.xml
//     2. HermiT consistency + unsatisfiable classes on the TBox
//     3. HermiT on TBox + example ABox (consistency)
//     4. negative OWL tests: each fixtures/invalid-owl/*.ttl must make it INCONSISTENT
//     5. ROBOT report (ontology QC)
//   Results → docs/status/reasoner.json
// Other reasoners (e.g. DEC) can be plugged in via smtg.config.json → reasoners.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { pipeline } from 'node:stream/promises';
import { Readable } from 'node:stream';
import N3 from 'n3';
import { p, CONFIG, ensureDir, writeJSON, log, ROOT } from '../lib/common.mjs';

const TOOLS = ensureDir(p('.tools'));
const JRE_DIR = path.join(TOOLS, 'jre');
const ROBOT_JAR = path.join(TOOLS, 'robot.jar');
const JRE_URL = 'https://api.adoptium.net/v3/binary/latest/21/ga/linux/x64/jre/hotspot/normal/eclipse';
const ROBOT_URL = 'https://github.com/ontodev/robot/releases/latest/download/robot.jar';
const reasonerName = process.argv.includes('--reasoner') ? process.argv[process.argv.indexOf('--reasoner') + 1] : CONFIG.reasoners.default;
const reasoner = CONFIG.reasoners.available[reasonerName];
const WORK = ensureDir(p('data', 'reasoning'));

async function download(url, dest) {
  log(`downloading ${url}`);
  const res = await fetch(url, { headers: { 'User-Agent': CONFIG.userAgent }, redirect: 'follow' });
  if (!res.ok) throw new Error(`${res.status} for ${url}`);
  await pipeline(Readable.fromWeb(res.body), fs.createWriteStream(dest + '.part'));
  fs.renameSync(dest + '.part', dest);
}

function java() {
  if (fs.existsSync(JRE_DIR)) {
    const dir = fs.readdirSync(JRE_DIR).find((d) => fs.existsSync(path.join(JRE_DIR, d, 'bin', 'java')));
    if (dir) return path.join(JRE_DIR, dir, 'bin', 'java');
  }
  return null;
}

async function bootstrap() {
  if (!java()) {
    ensureDir(JRE_DIR);
    const tgz = path.join(TOOLS, 'jre.tar.gz');
    await download(JRE_URL, tgz);
    const r = spawnSync('tar', ['-xzf', tgz, '-C', JRE_DIR], { stdio: 'inherit' });
    if (r.status !== 0) throw new Error('tar failed');
    fs.unlinkSync(tgz);
  }
  if (!fs.existsSync(ROBOT_JAR)) await download(ROBOT_URL, ROBOT_JAR);
  const v = spawnSync(java(), ['-version'], { encoding: 'utf8' });
  log('java:', (v.stderr || v.stdout).split('\n')[0]);
}

function robot(args, { quiet = false } = {}) {
  const r = spawnSync(java(), ['-Xmx4g', '-jar', ROBOT_JAR, ...args], { encoding: 'utf8', cwd: ROOT, maxBuffer: 64 * 1024 * 1024 });
  const out = `${r.stdout ?? ''}${r.stderr ?? ''}`.trim();
  if (!quiet) log(`robot ${args.slice(0, 2).join(' ')} … → exit ${r.status}`);
  return { status: r.status, out };
}

// Catalog mapping module IRIs → local files (also used by Protégé).
function writeCatalog() {
  const entries = [];
  const dirs = ['ontology', 'ontology/vocab', 'ontology/views'];
  for (const d of dirs) {
    for (const f of fs.readdirSync(p(d)).filter((x) => x.endsWith('.ttl'))) {
      const quads = new N3.Parser().parse(fs.readFileSync(p(d, f), 'utf8'));
      const ont = quads.find((q) => q.predicate.value.endsWith('#type') && q.object.value === 'http://www.w3.org/2002/07/owl#Ontology');
      if (ont) entries.push([ont.subject.value, path.relative(p('ontology'), p(d, f))]);
    }
  }
  const xml = `<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<!-- GENERATED by tools/reason/reason.mjs: maps SMTG module IRIs to local files (ROBOT, Protégé). -->
<catalog prefer="public" xmlns="urn:oasis:names:tc:entity:xmlns:xml:catalog">
${entries.map(([iri, file]) => `  <uri name="${iri}" uri="${file}"/>`).join('\n')}
</catalog>
`;
  fs.writeFileSync(p('ontology', 'catalog-v001.xml'), xml);
  return entries.length;
}

const result = { generatedAt: new Date().toISOString(), reasoner: reasonerName, steps: [] };
const step = (name, ok, detail) => { result.steps.push({ name, ok, ...detail }); log(`${ok ? '✓' : '✗'} ${name}`); };

if (!reasoner) throw new Error(`unknown reasoner ${reasonerName}`);
if (reasoner.kind === 'external') {
  if (!reasoner.command) {
    log(`reasoner "${reasonerName}" is a placeholder (no command configured in smtg.config.json)`);
    process.exit(0);
  }
}

await bootstrap();
const nModules = writeCatalog();
const catalog = ['--catalog', 'ontology/catalog-v001.xml'];
const merged = path.join(WORK, 'smtg-merged.owl');

let r = robot(['merge', ...catalog, '--input', 'ontology/smtg.ttl', '--output', merged]);
step('merge TBox via owl:imports closure', r.status === 0, { modules: nModules, log: r.out.slice(-2000) });

if (r.status === 0) {
  const unsat = path.join(WORK, 'unsatisfiable.txt');
  r = robot(['reason', '--input', merged, '--reasoner', reasoner.arg ?? 'hermit', '--dump-unsatisfiable', unsat, '--output', path.join(WORK, 'smtg-reasoned.owl')]);
  const unsatisfiable = fs.existsSync(unsat) ? fs.readFileSync(unsat, 'utf8').split('\n').filter(Boolean) : [];
  result.consistent = !/inconsistent/i.test(r.out) && r.status === 0;
  result.unsatisfiable = unsatisfiable;
  step(`TBox reasoning (${reasonerName}): consistent, no unsatisfiable classes`, r.status === 0 && unsatisfiable.length === 0, { log: r.out.slice(-3000) });

  // TBox + example ABox
  const exInputs = fs.readdirSync(p('examples')).filter((f) => f.endsWith('.ttl')).flatMap((f) => ['--input', `examples/${f}`]);
  const abox = path.join(WORK, 'smtg-with-examples.owl');
  r = robot(['merge', '--input', merged, ...exInputs, '--output', abox], { quiet: true });
  if (r.status === 0) {
    r = robot(['reason', '--input', abox, '--reasoner', reasoner.arg ?? 'hermit', '--output', path.join(WORK, 'smtg-with-examples-reasoned.owl')]);
    result.aboxConsistent = r.status === 0;
    step('TBox + example ABox consistent', r.status === 0, { log: r.out.slice(-3000) });
  } else step('merge TBox + examples', false, { log: r.out.slice(-2000) });

  // Negative OWL tests
  result.negative = [];
  for (const f of fs.readdirSync(p('fixtures', 'invalid-owl')).filter((x) => x.endsWith('.ttl'))) {
    const neg = path.join(WORK, `neg-${f}.owl`);
    robot(['merge', '--input', merged, '--input', `fixtures/invalid-owl/${f}`, '--output', neg], { quiet: true });
    const rr = robot(['reason', '--input', neg, '--reasoner', reasoner.arg ?? 'hermit', '--output', neg + '.out'], { quiet: true });
    const inconsistent = rr.status !== 0 && /inconsistent/i.test(rr.out);
    result.negative.push({ file: `fixtures/invalid-owl/${f}`, inconsistentAsExpected: inconsistent, log: rr.out.split('\n').filter((l) => /inconsisten|ERROR/i.test(l)).slice(0, 5) });
    step(`negative OWL test ${f} is inconsistent`, inconsistent, {});
  }

  // QC report
  const rep = path.join(WORK, 'robot-report.tsv');
  r = robot(['report', '--input', merged, '--fail-on', 'none', '--output', rep]);
  if (fs.existsSync(rep)) {
    const rows = fs.readFileSync(rep, 'utf8').trim().split('\n').slice(1).map((l) => l.split('\t'));
    const byRule = {};
    for (const [level, rule] of rows) byRule[`${level} ${rule}`] = (byRule[`${level} ${rule}`] ?? 0) + 1;
    result.report = { rows: rows.length, byRule, sample: rows.slice(0, 40) };
    step('ROBOT report generated', true, { byRule });
  }
}

writeJSON(p('docs', 'status', 'reasoner.json'), result);
const ok = result.steps.every((s) => s.ok || s.name.startsWith('ROBOT report'));
log(ok ? 'REASONING CHECKS PASSED' : 'REASONING CHECKS: SEE FAILURES ABOVE');
process.exitCode = ok ? 0 : 1;
