#!/usr/bin/env node
// Rule-based materialisation of selected inferences (PLAN §8.3): SPARQL CONSTRUCT rules in rules/*.rq,
// each implementing one documented OWL axiom of the ontology, run to a fixpoint over the ontology,
// the vocabularies and the example ABox. Results go to a SEPARATE inferred graph/file — never into
// the asserted examples — together with a PROV InferenceActivity describing the run.
//   inferred/rules.ttl          inferred triples (graph https://w3id.org/smtg/graph/inferred/rules)
//   inferred/_provenance.ttl    the InferenceActivity (rules used, inputs, counts, versions)
//   docs/status/inference.json  per-rule counts for the docs
//   docs/ontology/inference-rules.md  generated rule catalogue
import fs from 'node:fs';
import path from 'node:path';
import oxigraph from 'oxigraph';
import N3 from 'n3';
import { p, CONFIG, ensureDir, writeJSON, log } from '../lib/common.mjs';
import { PREFIXES } from '../lib/rdf.mjs';

export const INFERRED_GRAPH = 'https://w3id.org/smtg/graph/inferred/rules';
const MAX_ITERATIONS = 10;

const store = new oxigraph.Store();
const load = (dir) => {
  if (!fs.existsSync(p(dir))) return;
  for (const f of fs.readdirSync(p(dir)).filter((x) => x.endsWith('.ttl'))) store.load(fs.readFileSync(p(dir, f), 'utf8'), { format: 'text/turtle', base_iri: 'https://w3id.org/smtg/' });
};
['ontology', 'ontology/vocab', 'examples'].forEach(load);
const assertedSize = store.size;

const rules = fs
  .readdirSync(p('rules'))
  .filter((f) => f.endsWith('.rq'))
  .sort()
  .map((f) => {
    const text = fs.readFileSync(p('rules', f), 'utf8');
    const meta = Object.fromEntries([...text.matchAll(/^# (\w+):\s*(.*)$/gm)].map((m) => [m[1], m[2].trim()]));
    return { file: `rules/${f}`, id: meta.id ?? path.basename(f, '.rq'), title: meta.title, implements: meta.implements, order: Number(meta.order ?? 1), query: text.split('\n').filter((l) => !l.startsWith('#')).join('\n'), count: 0 };
  })
  .sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));

// Fixpoint: new triples are added to the working store so later rules (and later rounds) see them.
const key = (q) => `${q.subject.value}|${q.predicate.value}|${q.object.termType}:${q.object.value}`;
const inferred = new Map(); // key -> {quad, rule}
let iteration = 0;
for (; iteration < MAX_ITERATIONS; iteration++) {
  let added = 0;
  for (const r of rules) {
    for (const q of store.query(r.query)) {
      const triple = oxigraph.triple(q.subject, q.predicate, q.object);
      if (store.has(oxigraph.quad(q.subject, q.predicate, q.object, oxigraph.defaultGraph()))) continue;
      store.add(oxigraph.quad(q.subject, q.predicate, q.object, oxigraph.defaultGraph()));
      inferred.set(key(triple), { quad: q, rule: r.id });
      r.count++;
      added++;
    }
  }
  log(`iteration ${iteration + 1}: ${added} new triples`);
  if (!added) break;
}
if (iteration === MAX_ITERATIONS) throw new Error('materialisation did not reach a fixpoint');

// Write the inferred graph (grouped by rule, deterministic order)
ensureDir(p('inferred'));
const N = N3.DataFactory;
const toN3 = (t) => (t.termType === 'NamedNode' ? N.namedNode(t.value) : t.termType === 'BlankNode' ? N.blankNode(t.value) : N.literal(t.value, t.language || (t.datatype ? N.namedNode(t.datatype.value) : undefined)));
const writeTurtle = (file, quads, header) =>
  new Promise((res, rej) => {
    const w = new N3.Writer({ prefixes: { ...PREFIXES, smtgid: 'https://w3id.org/smtg/id/', smtgv: 'https://w3id.org/smtg/vocab/' } });
    w.addQuads(quads);
    w.end((e, body) => (e ? rej(e) : res(fs.writeFileSync(file, `${header}\n\n${body}`))));
  });
const sorted = [...inferred.values()].sort((a, b) => (a.rule + key(a.quad)).localeCompare(b.rule + key(b.quad)));
await writeTurtle(
  p('inferred', 'rules.ttl'),
  sorted.map(({ quad: q }) => N.quad(toN3(q.subject), toN3(q.predicate), toN3(q.object))),
  `# GENERATED by tools/reason/materialize.mjs (npm run infer) — do not edit.\n# Inferred graph <${INFERRED_GRAPH}>: triples entailed by the OWL axioms named in rules/*.rq,\n# materialised from the asserted examples. Never merged into source graphs. Provenance: inferred/_provenance.ttl`,
);

// Provenance of the run
const now = new Date().toISOString();
const S = PREFIXES.smtg, PROV = PREFIXES.prov, RDFS = PREFIXES.rdfs, XSD = PREFIXES.xsd;
const act = N.namedNode(`https://w3id.org/smtg/id/activity/inference-rules-${now.slice(0, 10)}`);
const graph = N.namedNode(INFERRED_GRAPH);
const pq = [
  N.quad(act, N.namedNode(PREFIXES.rdf + 'type'), N.namedNode(S + 'InferenceActivity')),
  N.quad(act, N.namedNode(RDFS + 'label'), N.literal(`Rule materialisation (${rules.length} rules, ${inferred.size} triples)`)),
  N.quad(act, N.namedNode(PROV + 'endedAtTime'), N.literal(now, N.namedNode(XSD + 'dateTime'))),
  N.quad(act, N.namedNode(PROV + 'wasAssociatedWith'), N.namedNode('https://w3id.org/smtg/id/agent/smtg-pipeline')),
  N.quad(act, N.namedNode(S + 'ontologyVersionUsed'), N.literal(CONFIG.ontologyVersion)),
  N.quad(graph, N.namedNode(PREFIXES.rdf + 'type'), N.namedNode(PROV + 'Entity')),
  N.quad(graph, N.namedNode(PROV + 'wasGeneratedBy'), act),
  N.quad(graph, N.namedNode(RDFS + 'label'), N.literal('Inferred graph: rule materialisation')),
  ...rules.map((r) => N.quad(act, N.namedNode(PROV + 'used'), N.namedNode(`https://w3id.org/smtg/id/rule/${r.id}`))),
  ...rules.flatMap((r) => [
    N.quad(N.namedNode(`https://w3id.org/smtg/id/rule/${r.id}`), N.namedNode(RDFS + 'label'), N.literal(r.title ?? r.id)),
    N.quad(N.namedNode(`https://w3id.org/smtg/id/rule/${r.id}`), N.namedNode(RDFS + 'comment'), N.literal(`Implements: ${r.implements ?? '—'}. Source: ${r.file}. Triples: ${r.count}.`)),
  ]),
];
await writeTurtle(p('inferred', '_provenance.ttl'), pq, '# GENERATED by tools/reason/materialize.mjs — provenance of the inferred graph.');

writeJSON(p('docs', 'status', 'inference.json'), { generatedAt: now, graph: INFERRED_GRAPH, assertedTriples: assertedSize, inferredTriples: inferred.size, iterations: iteration + 1, rules: rules.map(({ query, ...r }) => r) });
fs.writeFileSync(
  p('docs', 'ontology', 'inference-rules.md'),
  `# Inference rules

GENERATED by \`npm run infer\` from \`rules/*.rq\` — edit the rules, not this page.

Selected OWL axioms of the ontology are **materialised** by SPARQL CONSTRUCT rules, run to a fixpoint (${iteration + 1} rounds) over the ontology, the vocabularies and the example ABox (${assertedSize} asserted triples). The ${inferred.size} inferred triples go to their own graph, \`${INFERRED_GRAPH}\` (\`inferred/rules.ttl\`), with a PROV \`InferenceActivity\` (\`inferred/_provenance.ttl\`). They are never merged into the source graphs. The OWL axioms themselves are checked by HermiT (\`npm run reason\`); each rule names the axiom it implements, so both can be reviewed side by side (PLAN §8.3).

| Rule | What it derives | OWL axiom it implements | Triples |
|---|---|---|---|
${rules.map((r) => `| **${r.id.replace(/-/g, '\u2011')}** | ${r.title ?? ''} | ${(r.implements ?? '').replace(/\|/g, '\\|')} | ${r.count} |`).join('\n')}
`,
);
log(`inferred ${inferred.size} triples from ${assertedSize} asserted, ${rules.length} rules → inferred/rules.ttl`);
