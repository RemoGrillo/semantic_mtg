#!/usr/bin/env node
// Run the competency questions (queries/competency/*.rq) against the ontology +
// vocabularies + example ABox in an in-memory Oxigraph store (no reasoning:
// these are plain SPARQL answers over asserted data). Writes
// docs/status/cq-results.json and docs/ontology/competency-questions.md.
import fs from 'node:fs';
import path from 'node:path';
import oxigraph from 'oxigraph';
import { p, writeJSON, log } from '../lib/common.mjs';

const store = new oxigraph.Store();
const load = (dir) => {
  for (const f of fs.readdirSync(p(dir)).filter((x) => x.endsWith('.ttl'))) store.load(fs.readFileSync(p(dir, f), 'utf8'), { format: 'text/turtle', base_iri: 'https://w3id.org/smtg/' });
};
['ontology', 'ontology/vocab', 'examples'].forEach(load);
// Inferred triples (npm run infer) live in their own named graph; their provenance in the default graph.
const INFERRED_GRAPH = 'https://w3id.org/smtg/graph/inferred/rules';
if (fs.existsSync(p('inferred', 'rules.ttl'))) store.load(fs.readFileSync(p('inferred', 'rules.ttl'), 'utf8'), { format: 'text/turtle', to_graph_name: oxigraph.namedNode(INFERRED_GRAPH) });
if (fs.existsSync(p('inferred', '_provenance.ttl'))) store.load(fs.readFileSync(p('inferred', '_provenance.ttl'), 'utf8'), { format: 'text/turtle' });
log(`store loaded: ${store.size} triples (asserted in the default graph; inferred in <${INFERRED_GRAPH}>)`);

const short = (v) => v
  .replace('https://w3id.org/smtg/ontology#', 'smtg:')
  .replace('https://w3id.org/smtg/vocab/', 'smtgv:')
  .replace('https://w3id.org/smtg/id/', 'smtgid:');

const results = [];
for (const f of fs.readdirSync(p('queries', 'competency')).filter((x) => x.endsWith('.rq')).sort()) {
  const text = fs.readFileSync(p('queries', 'competency', f), 'utf8');
  const meta = Object.fromEntries([...text.matchAll(/^# (\w+):\s*(.*)$/gm)].map((m) => [m[1], m[2].trim()]));
  const query = text.split('\n').filter((l) => !l.startsWith('#')).join('\n').trim();
  let rows = [], error = null;
  try {
    for (const b of store.query(query)) {
      const row = {};
      for (const [k, v] of b.entries()) row[k] = short(v.value);
      rows.push(row);
    }
  } catch (e) { error = e.message; }
  const exp = meta.expects ?? 'any';
  const pass = error ? false
    : exp === 'nonempty' ? rows.length > 0
    : exp === 'empty' ? rows.length === 0
    : exp.startsWith('count=') ? rows.length === Number(exp.slice(6))
    : true;
  results.push({ id: meta.id ?? path.basename(f, '.rq'), file: `queries/competency/${f}`, title: meta.title, question: meta.question, kind: meta.kind, expects: exp, modules: meta.modules, note: meta.note, rowCount: rows.length, rows: rows.slice(0, 25), pass, error, query });
  log(`${pass ? '✓' : '✗'} ${meta.id} (${rows.length} rows${error ? ', ERROR ' + error : ''})`);
}

writeJSON(p('docs', 'status', 'cq-results.json'), { generatedAt: new Date().toISOString(), triples: store.size, results });

const md = [`# Competency questions

GENERATED by \`npm run cq\` from \`queries/competency/*.rq\` on ${new Date().toISOString().slice(0, 10)} — edit the \`.rq\` files, not this page.
Answers are computed with plain SPARQL over the ontology, the generated vocabularies and the example ABox built from real fixtures (default graph). Triples materialised by the inference rules (\`npm run infer\`) are in the named graph \`<https://w3id.org/smtg/graph/inferred/rules>\`; questions that use them say so with a \`GRAPH\` clause.
Negative tests (kind \`negative\`) must return **no rows**.

| ID | Question | Kind | Expected | Rows | Result |
|---|---|---|---|---|---|
${results.map((r) => `| ${r.id} | ${r.question} | ${r.kind} | ${r.expects} | ${r.rowCount} | ${r.pass ? 'pass' : '**FAIL**'} |`).join('\n')}
`];
for (const r of results) {
  // the cards the question is about, shown as Scryfall images (link form [[…]] → image form [[!…]])
  const cards = [...new Set([...`${r.question ?? ''}`.matchAll(/\[\[([^!\][\n][^\][\n]*?)\]\]/g)].map((m) => m[1]))];
  md.push(`\n## ${r.id} — ${r.title}\n\n**Question.** ${r.question}\n\n${cards.length ? `${cards.map((c) => `[[!${c}]]`).join(' ')}\n\n` : ''}${r.note ? `*Note:* ${r.note}\n\n` : ''}Modules: ${r.modules ?? '—'} · kind: ${r.kind} · expects: ${r.expects} · **${r.pass ? 'pass' : 'FAIL'}** (${r.rowCount} rows)\n\n\`\`\`sparql\n${r.query}\n\`\`\`\n`);
  if (r.rows.length) {
    const cols = Object.keys(r.rows[0]);
    md.push(`| ${cols.join(' | ')} |\n|${cols.map(() => '---').join('|')}|\n${r.rows.slice(0, 10).map((row) => `| ${cols.map((c) => String(row[c] ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ').slice(0, 120)).join(' | ')} |`).join('\n')}\n`);
  }
}
fs.writeFileSync(p('docs', 'ontology', 'competency-questions.md'), md.join('\n'));
const failed = results.filter((r) => !r.pass);
log(`${results.length - failed.length}/${results.length} competency questions pass`);
process.exitCode = failed.length ? 1 : 0;
